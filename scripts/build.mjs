// Scans the photo folder, generates lightweight WebP thumbnails and writes
// the gallery manifest (data/gallery.js) consumed by index.html.
import { readdir, mkdir, writeFile, stat } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_DIR = "EXPO 2026 Byo";
const THUMB_DIR = "thumbs";
const THUMB_WIDTH = 640;
const IMAGE_RE = /\.(jpe?g|png|webp)$/i;

const slug = (s) => s.toLowerCase().replace(/expo 2026/g, "").trim().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const label = (s) => s.replace(/^EXPO 2026\s*/i, "").replace(/\b\w+/g, (w) => w[0] + w.slice(1).toLowerCase());

async function exists(p) {
  try { await stat(p); return true; } catch { return false; }
}

async function main() {
  const albumDirs = (await readdir(path.join(ROOT, SOURCE_DIR), { withFileTypes: true }))
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort((a, b) => {
      // Numbered days first, then the final day, then any named sessions.
      const rank = (n) => {
        const day = n.match(/\bDAY\s+(\d+)/i);
        if (day) return parseInt(day[1], 10);
        return /final/i.test(n) ? 900 : 1000;
      };
      return rank(a) - rank(b) || a.localeCompare(b);
    });

  const albums = [];
  for (const dir of albumDirs) {
    const id = slug(dir);
    const files = (await readdir(path.join(ROOT, SOURCE_DIR, dir))).filter((f) => IMAGE_RE.test(f)).sort();
    await mkdir(path.join(ROOT, THUMB_DIR, id), { recursive: true });

    const photos = [];
    for (const file of files) {
      const src = path.join(ROOT, SOURCE_DIR, dir, file);
      const thumbName = file.replace(IMAGE_RE, ".webp");
      const thumb = path.join(ROOT, THUMB_DIR, id, thumbName);
      const { size } = await stat(src);

      const img = sharp(src).rotate();
      const meta = await sharp(src).metadata();
      const swap = (meta.orientation ?? 1) >= 5;
      const w = swap ? meta.height : meta.width;
      const h = swap ? meta.width : meta.height;

      if (!(await exists(thumb))) {
        await img.resize({ width: THUMB_WIDTH, withoutEnlargement: true }).webp({ quality: 72 }).toFile(thumb);
      }

      photos.push({
        name: file,
        src: `${SOURCE_DIR}/${dir}/${file}`,
        thumb: `${THUMB_DIR}/${id}/${thumbName}`,
        w, h, size,
      });
    }
    console.log(`${dir}: ${photos.length} photos`);
    albums.push({ id, title: label(dir), photos });
  }

  await mkdir(path.join(ROOT, "data"), { recursive: true });
  const out = `// Generated by scripts/build.mjs - do not edit by hand.\nwindow.GALLERY = ${JSON.stringify({ albums })};\n`;
  await writeFile(path.join(ROOT, "data", "gallery.js"), out);
  const total = albums.reduce((n, a) => n + a.photos.length, 0);
  console.log(`Wrote data/gallery.js with ${total} photos across ${albums.length} albums.`);
}

main().catch((err) => { console.error(err); process.exit(1); });
